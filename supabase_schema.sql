create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'طالب',
  grade text not null default 'الثانوية العامة',
  daily_goal_minutes integer not null default 180,
  points integer not null default 0,
  streak integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#6D4AFF'
);
insert into public.subjects(name,color) values
