create table if not exists public.user_badges (
  user_id uuid not null references auth.users(id) on delete cascade,
  badge_id bigint not null references public.badges(id) on delete cascade,
  earned_at timestamptz not null default now(), primary key(user_id,badge_id)
);

alter table public.profiles enable row level security;
alter table public.study_sessions enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.subjects enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.badges enable row level security;
alter table public.user_badges enable row level security;

create policy "profile own" on public.profiles for all using (auth.uid()=id) with check (auth.uid()=id);
create policy "sessions own" on public.study_sessions for all using (auth.uid()=user_id) with check (auth.uid()=user_id);
create policy "attempts own" on public.quiz_attempts for all using (auth.uid()=user_id) with check (auth.uid()=user_id);
create policy "subjects readable" on public.subjects for select using (true);
create policy "quizzes readable" on public.quizzes for select using (true);
create policy "questions readable" on public.quiz_questions for select using (true);
create policy "badges readable" on public.badges for select using (true);
create policy "user badges own" on public.user_badges for select using (auth.uid()=user_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name) values (new.id, coalesce(new.raw_user_meta_data->>'full_name','طالب'));
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

