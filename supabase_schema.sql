on conflict (name) do nothing;

create table if not exists public.study_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint references public.subjects(id),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  duration_minutes integer not null default 0,
  completed boolean not null default false
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  subject_id bigint references public.subjects(id), title text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  question text not null, options jsonb not null, correct_index integer not null
);
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  score integer not null default 0, total integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.badges (
  id bigint generated by default as identity primary key,
  code text unique not null, title text not null, description text not null,
  icon text not null default '🏆'
);
